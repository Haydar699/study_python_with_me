# madlibs game 
# word game where players fill in the blanks to create a funny story

# fill in the blanks with user input 
name = input("Enter a name: ")
place = input("Enter a place: ")
adjective1 = input("Enter an adjective: ")
noun1 = input("Enter a noun: ")
adjective2 = input("Enter another adjective: ")
noun2 = input("Enter another noun: ")
adjective3 = input("Enter a third adjective: ")


print("Welcome to the Mad Libs Game!")
print(f"someday, a person named {name} went to the {place} to buy a {adjective1} {noun1}.")
print(f"on the way, {name} met a {adjective2} {noun2} who offered to help carry the {noun1}.")
print(f"together, they had a {adjective3} adventure and became best friends forever!")

