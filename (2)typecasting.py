# typecasting is the process of converting a variable from one data type to another. In Python, you can use built-in functions to perform typecasting. Here are some common typecasting functions: 
# int() - converts a value to an integer
# float() - converts a value to a float
# str() - converts a value to a string
# bool() - converts a value to a boolean

name = 'fatah'
age = 19
ipk = 3.7
student = True

type(name)
type(age)
type(ipk)
type(student)

print(type(name)) # <class 'str'>
print(type(student)) # <class 'bool'>

age = float(age) # convert age from int to float
print(age) # <class 'float'>

print(age)